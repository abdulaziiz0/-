// Helper to strip diacritics and normalize Arabic text for search matching
export function normalizeArabicText(text: string): string {
  if (!text) return '';
  return text
    // Remove Quranic annotation signs & zero-width characters
    .replace(/[\u06D6-\u06ED\u0610-\u061A\u200B-\u200F\uFEFF]/g, '')
    // Remove Tashkeel (diacritics: Fatha, Damma, Kasra, Sukun, Shadda, Tanwin)
    .replace(/[\u064B-\u065F\u0670]/g, '')
    // Normalize Alefs: أ إ آ -> ا
    .replace(/[أإآٱ]/g, 'ا')
    // Normalize Taa Marbuta: ة -> ه
    .replace(/ة/g, 'ه')
    // Normalize Ya: ى -> ي
    .replace(/ى/g, 'ي')
    // Normalize Waw with Hamza: ؤ -> و, Ya with Hamza: ئ -> ي
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    // Normalize spaces and remove punctuation
    .replace(/[«»""''،؛؟.,!;:()\[\]\-\/\\—–]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

